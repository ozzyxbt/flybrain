GLYPH_W, GLYPH_H, SPACING = 5, 7, 1
SUPPORTED = frozenset(GLYPHS)


def supported(text: str) -> bool:
    return all(ch in SUPPORTED for ch in text.upper())


def unsupported_characters(text: str) -> str:
    return "".join(sorted({ch for ch in text.upper() if ch not in SUPPORTED}))


def text_width(text: str, scale: int = 1) -> int:
    n = len(text)
    return (n * GLYPH_W + max(0, n - 1) * SPACING) * scale if n else 0


def text_height(scale: int = 1) -> int:
    return GLYPH_H * scale


def draw_text(frame: np.ndarray, x: int, y: int, text: str, color, scale: int = 1):
    """Blit uppercase text at (x, y). Pixels outside the frame are dropped."""
    h, w = frame.shape[:2]
    color = np.asarray(color, dtype=np.uint8)
    cx = x
    for ch in text.upper():
        rows = GLYPHS[ch]
        for r, row in enumerate(rows):
            for c, bit in enumerate(row):
                if bit != "#":
                    continue
                y0, x0 = y + r * scale, cx + c * scale
                y1, x1 = min(h, y0 + scale), min(w, x0 + scale)
                if y0 < h and x0 < w and y0 >= 0 and x0 >= 0:
                    frame[y0:y1, x0:x1] = color
        cx += (GLYPH_W + SPACING) * scale


def wrap(text: str, max_chars: int) -> list:
    words = text.upper().split(" ")
    lines, current = [], ""
    for word in words:
        candidate = word if not current else current + " " + word
        if len(candidate) <= max_chars:
            current = candidate
        else:
            if current:
                lines.append(current)
            current = word[:max_chars]
    if current:
        lines.append(current)
    return lines
